function resolveLanguage(preference, systemLocale) {
    if (preference === "pt-BR" || preference === "en") return preference
    var loc = String(systemLocale || "").toLowerCase()
    if (loc.indexOf("pt") === 0) return "pt-BR"
    return "en"
}

function t(lang, key, vars) {
    var dict = STRINGS[lang] || STRINGS["en"]
    var text = dict[key] !== undefined ? dict[key] : (STRINGS["en"][key] || key)
    if (vars && typeof vars === "object") {
        for (var k in vars) {
            if (Object.prototype.hasOwnProperty.call(vars, k)) {
                text = text.replace("{" + k + "}", String(vars[k]))
            }
        }
    }
    return text
}
